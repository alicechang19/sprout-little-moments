// The Blender pipeline for the imported (scanned) Sprouts. Blender files are the source; models/web is built from them.
//   node tools/blend.mjs make <id...>     scan -> models/blend/<id>/<id>.blend (runs tools/rig-imported.mjs --blend first)
//   node tools/blend.mjs export <id...>   models/blend/<id>/<id>.blend -> models/web/<id>-model.js and textures
// Edit the .blend in Blender (weights, bones, shape, the "lids" shape key); textures are the PNGs beside it
// (save painted images back to them). Set BLENDER if Blender isn't at /Applications/Blender.app.
import { NodeIO } from '@gltf-transform/core';
import { ALL_EXTENSIONS } from '@gltf-transform/extensions';
import { dedup, prune, quantize } from '@gltf-transform/functions';
import { execFileSync } from 'node:child_process';
import { existsSync } from 'node:fs';
import { readFile, writeFile, copyFile, readdir } from 'node:fs/promises';
import { fileURLToPath } from 'node:url';
import { gzipSync } from 'node:zlib';
import sharp from 'sharp';

const BLENDER = process.env.BLENDER ?? '/Applications/Blender.app/Contents/MacOS/Blender';
const at = (p) => fileURLToPath(new URL(`../${p}`, import.meta.url));
const [cmd, ...ids] = process.argv.slice(2);
const blender = (...args) => execFileSync(BLENDER, ['-b', '--factory-startup', ...args], { stdio: ['ignore', 'inherit', 'inherit'] });

async function make(id) {
  execFileSync('node', ['--max-old-space-size=12000', at('tools/rig-imported.mjs'), id, '--blend'], { stdio: 'inherit' });
  blender('-P', at('tools/blender/make_blend.py'), '--', id);
}

async function exportWeb(id) {
  const dir = `models/blend/${id}`;
  // the .blend files aren't in git; without this check Blender carries on with an empty scene
  if (!existsSync(at(`${dir}/${id}.blend`))) throw new Error(`No ${dir}/${id}.blend (make it first: node tools/blend.mjs make ${id})`);
  blender(at(`${dir}/${id}.blend`), '-P', at('tools/blender/export_glb.py'), '--', id);
  // the same packing as tools/rig-imported.mjs: quantized, gzip, base64 (decoded in the page by src/kit.js)
  const io = new NodeIO().registerExtensions(ALL_EXTENSIONS);
  const doc = await io.read(at(`${dir}/${id}-export.glb`));
  await doc.transform(dedup(), prune({ keepLeaves: true, keepAttributes: true }), quantize({ quantizePosition: 16, quantizeNormal: 12, quantizeTexcoord: 16 }));
  const bytes = await io.writeBinary(doc);
  const packed = gzipSync(bytes, { level: 9 });
  await writeFile(at(`models/web/${id}-model.js`), `// Generated by tools/blend.mjs from models/blend/${id}/${id}.blend. Skinned, quantized GLB, gzip, base64.\nexport const gzip = true;\nexport default '${packed.toString('base64')}';\n`);
  // textures: the lossless PNGs as webp, at the rigger's qualities (normal maps show compression as blotchy shading)
  const sizes = [];
  for (const [k, quality] of [['color', 90], ['normal', 94], ['orm', 88]]) {
    const buf = await sharp(await readFile(at(`${dir}/${id}-${k}.png`))).removeAlpha().webp({ quality, effort: 6 }).toBuffer();
    await writeFile(at(`models/web/${id}-${k}.webp`), buf);
    sizes.push(`${k} ${(buf.byteLength / 1024).toFixed(0)} KB`);
  }
  // closed-eye crops (painted-eye Sprouts only) are made by the rigger and ship as they are
  for (const f of (await readdir(at(dir))).filter((f) => f.startsWith(`${id}-closed`))) await copyFile(at(`${dir}/${f}`), at(`models/web/${f}`));
  console.log(`${id}: ${(bytes.byteLength / 1024).toFixed(0)} KB skinned model, ${(packed.byteLength / 1024).toFixed(0)} KB gzipped; ${sizes.join(', ')}`);
}

const run = { make, export: exportWeb }[cmd];
if (!run || !ids.length) throw new Error('Usage: node tools/blend.mjs <make|export> <id...>');
for (const id of ids) await run(id);
